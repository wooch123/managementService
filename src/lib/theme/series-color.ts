/**
 * 계열(series) 색 — 다섯 색을 **되풀이하지 않고** 필요한 만큼 늘린다.
 *
 * ── 왜 필요했나 ────────────────────────────────────────────────────────────────
 * 테마가 주는 차트 색은 `--chart-1`~`--chart-5` 다섯 개다. 그동안은 `(i % 5) + 1`로 돌려
 * 썼는데, 계열이 여섯을 넘으면 **같은 색이 한 그래프 안에 두 번** 나온다. 누적 막대에서는
 * 이게 특히 나쁘다 — 한 막대 안에 같은 색 층이 두 번 있으면 그 사이에 낀 층들이 하나의 띠처럼
 * 묶여 보여, 층이 볼록하게 솟은 것 같은 착시가 생긴다(실측: '주간 접수'는 계열 7개에 색 5개,
 * 6·7번째가 1·2번과 완전히 같은 색이었다).
 *
 * ── 어떻게 늘리나 ──────────────────────────────────────────────────────────────
 * 여섯 번째부터는 같은 색을 **카드 바탕 쪽으로 섞어** 한 단계씩 옅게 만든다. 색상각은 그대로라
 * 계열의 성격은 유지되고, 밝기가 달라 옆에 놓아도 구별된다. 새 색을 지어내지 않으므로 어떤
 * 테마에서도 그 테마의 색 안에 머문다.
 *
 *   1~5번   --chart-1 … --chart-5            그대로
 *   6~10번  같은 색 68% + 카드 바탕 32%       한 단계 옅게
 *   11~15번 같은 색 46% + 카드 바탕 54%       두 단계 옅게
 *
 * 바탕으로 `--card`를 쓰는 이유: 차트가 얹히는 면이 카드라, 그쪽으로 섞어야 라이트에서는
 * 밝아지고 다크에서는 어두워져 **두 테마 모두에서 자연스럽게 옅어진다**. 흰색·검정을 박으면
 * 한쪽 테마에서만 맞는다.
 */

/** 테마가 주는 기본 색의 개수. */
export const BASE_CHART_COLORS = 5;

/** 한 바퀴 돌 때마다 바탕에 얼마나 가까워지는지(%). */
const FADE_STEPS = [100, 68, 46, 32];

/**
 * `index`번째 계열의 색을 CSS 값으로 돌려준다.
 *
 * 그래프 하나 안에서 **인덱스가 같으면 늘 같은 색**이다 — 범례·막대·표가 같은 함수를 쓰면
 * 서로 어긋나지 않는다.
 */
export function seriesColor(index: number): string {
  const base = `var(--chart-${(index % BASE_CHART_COLORS) + 1})`;
  const round = Math.floor(index / BASE_CHART_COLORS);
  if (round === 0) return base;
  // 준비한 단계를 넘어가면 마지막 단계에 머문다 — 더 옅게 하면 바탕과 구별되지 않는다.
  const weight = FADE_STEPS[Math.min(round, FADE_STEPS.length - 1)];
  return `color-mix(in oklab, ${base} ${weight}%, var(--card))`;
}
